def index(request):
    return render(request, 'html/index.html', context={'posts': posts})

def post_detail(request, id):
    post = next((post for post in posts if post['id'] == id), None)
    return render(request, 'html/detail.html', context={'post': post})

def category_posts(request, category_slug):
    category_posts = [post for post in posts if post['category'] == category_slug]
    return render(request, 'html/category.html', context={'posts': category_posts, 'category': category_slug})